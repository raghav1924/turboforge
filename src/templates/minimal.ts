import { ProjectConfig, TemplateFile } from '../core/types.js';

export function generateMinimalTemplate(config: ProjectConfig): TemplateFile[] {
  const files: TemplateFile[] = [];

  files.push({
    path: 'apps/web/package.json',
    content: JSON.stringify(
      {
        name: 'web',
        version: '0.1.0',
        private: true,
        scripts: {
          dev: 'next dev --port 3000',
          build: 'next build',
          start: 'next start',
        },
        dependencies: {
          next: '^15.0.3',
          react: '^19.0.0',
          'react-dom': '^19.0.0',
          '@repo/ui': 'workspace:*',
        },
        devDependencies: {
          '@repo/tsconfig': 'workspace:*',
          '@types/node': '^22.10.1',
          '@types/react': '^19.0.0',
          tailwindcss: '^3.4.15',
          typescript: '^5.5.4',
        },
      },
      null,
      2
    ) + '\n',
  });

  files.push({
    path: 'apps/web/src/app/page.tsx',
    content: `import { Button } from '@repo/ui/components/button';

export default function Page() {
  return (
    <main className="flex flex-col items-center justify-center min-h-screen bg-neutral-950 text-white p-6">
      <h1 className="text-3xl font-bold mb-4">${config.name}</h1>
      <p className="text-neutral-400 mb-6">Minimal Turborepo monorepo generated by Turboforge.</p>
      <Button variant="primary">Get Started</Button>
    </main>
  );
}
`,
  });

  return files;
}

